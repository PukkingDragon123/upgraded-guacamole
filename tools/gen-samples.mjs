// Embeds the recorded audio (assets/sfx/*.ogg one-shots + loop beds, assets/music/*.ogg tracks; CC0 /
// public domain, see assets/sfx/CREDITS.md) into src/core/samples-data.js so the single-file build needs
// no asset fetch. Clip id = file name without .ogg. Run after changing assets: node tools/gen-samples.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lines = [];
let bytes = 0;
for (const sub of ['assets/sfx', 'assets/music']) {
  const dir = join(root, sub);
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).filter((n) => n.endsWith('.ogg')).sort()) {
    const buf = readFileSync(join(dir, f));
    bytes += buf.length;
    lines.push(`  ${JSON.stringify(f.replace(/\.ogg$/, ''))}: ${JSON.stringify(buf.toString('base64'))},`);
  }
}
writeFileSync(join(root, 'src/core/samples-data.js'),
  `// GENERATED by tools/gen-samples.mjs from assets/sfx + assets/music (CC0 / public domain). Do not edit by hand.\nexport const SAMPLE_DATA = {\n${lines.join('\n')}\n};\n`);
console.log(`embedded ${lines.length} clips, ${(bytes / 1048576).toFixed(2)} MB of OGG (${(bytes * 4 / 3 / 1048576).toFixed(2)} MB as base64)`);
