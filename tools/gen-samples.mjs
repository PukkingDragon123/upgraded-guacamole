// Embeds assets/sfx/*.ogg (CC0 recordings, see assets/sfx/CREDITS.md) into src/core/samples-data.js
// so the single-file build needs no asset fetch. Run after changing assets/sfx: node tools/gen-samples.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/sfx');
const files = readdirSync(dir).filter((f) => f.endsWith('.ogg')).sort();
const lines = files.map((f) => `  ${JSON.stringify(f.replace(/\.ogg$/, ''))}: ${JSON.stringify(readFileSync(join(dir, f)).toString('base64'))},`);
writeFileSync(join(root, 'src/core/samples-data.js'),
  `// GENERATED by tools/gen-samples.mjs from assets/sfx (CC0). Do not edit by hand.\nexport const SAMPLE_DATA = {\n${lines.join('\n')}\n};\n`);
console.log(`embedded ${files.length} samples`);
