const GROW = {
  fireflower: 1.3, neonpunk: 1.3, floorlava: 1.3, fishsticks: 1.35, icebabycod: 1.3,
  eldershark: 1, moltenleviathan: 1, mayorgrouper: 1, kingconger: 1.1, preciouseel: 1.2,
  snowcrab: 1.2, steamcrab: 1.2, taxicrab: 1.2, auroraray: 1.05, adbreakray: 1.15, ripandtear: 1.08, badwolffish: 1.1, gottagofast: 1.08,
};
const GROW_KEYS = ['len', 'h', 'spread', 'r', 'w', 'reach', 'size', 'spacing', 'rx', 'ry', 'scaleSize', 'spikes', 'tentacles', 'curl', 'thick'];
function grow(o, f, eyeF, key = '') {
  if (Array.isArray(o)) return o.map((v) => grow(v, f, eyeF, key));
  if (!o || typeof o !== 'object') return o;
  const out = {};
  for (const [k, v] of Object.entries(o)) {
    if (typeof v === 'number' && GROW_KEYS.includes(k)) out[k] = +(v * (k === 'r' && (key === 'eye' || key === 'moreEyes') ? f * eyeF : key === 'tail' && (k === 'len' || k === 'spread') ? f * 1.12 : f)).toFixed(2);
    else if (typeof v === 'object') out[k] = grow(v, f, eyeF, k);
    else out[k] = v;
  }
  return out;
}
for (const sp of S) {
  const f = GROW[sp.id] ?? 1.25;
  if (f !== 1) sp.look = grow(sp.look, f, sp.look.kind ? 1 : 1.08);
}

